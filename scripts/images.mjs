/*
  IMAGE PIPELINE — run with:  npm run images

  What it does (so the site loads fast on phones):
  1. Photos in assets/source/images/  → public/images/<name>-<width>.avif + .webp
     in several widths. The browser picks the smallest file that looks sharp.
  2. Logos in assets/source/brand/    → trimmed (empty space removed) PNGs in public/brand/
  3. Writes app/content/images.generated.ts with each photo's size, so the
     <Image> component can reserve space and the page doesn't jump while loading.

  To add a photo: drop it in assets/source/images/ with a lowercase-hyphen name
  (e.g. destination-kerala.jpg), then run `npm run images`.
*/
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcImages = path.join(root, "assets/source/images");
const srcBrand = path.join(root, "assets/source/brand");
const outImages = path.join(root, "public/images");
const outBrand = path.join(root, "public/brand");
const manifestFile = path.join(root, "app/content/images.generated.ts");

const WIDTHS = [480, 800, 1200, 1600];
const isImage = (f) => /\.(jpe?g|png|webp|avif)$/i.test(f);

await mkdir(outImages, { recursive: true });
await mkdir(outBrand, { recursive: true });

// 1 + 3: photos
const manifest = {};
for (const file of (await readdir(srcImages)).filter(isImage).sort()) {
  const name = file.replace(/\.[^.]+$/, "");
  const input = sharp(path.join(srcImages, file)).rotate(); // respect camera orientation
  const { width, height } = await input.metadata();
  const widths = WIDTHS.filter((w) => w <= width);
  if (widths.length === 0 || widths.at(-1) < width) widths.push(Math.min(width, 2000));

  for (const w of widths) {
    const resized = input.clone().resize({ width: w });
    await resized.clone().avif({ quality: 55, effort: 4 }).toFile(path.join(outImages, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: 78 }).toFile(path.join(outImages, `${name}-${w}.webp`));
  }
  manifest[name] = { width, height, widths };
  console.log(`✓ ${name}  (${width}×${height}) → ${widths.join(", ")}px`);
}

// 2: logos
for (const file of (await readdir(srcBrand)).filter(isImage).sort()) {
  await sharp(path.join(srcBrand, file))
    .trim()
    .resize({ width: 720, withoutEnlargement: true })
    .png({ compressionLevel: 9 })
    .toFile(path.join(outBrand, file.replace(/\.[^.]+$/, ".png")));
  console.log(`✓ logo ${file} (trimmed)`);
}

const ts = `// AUTO-GENERATED by scripts/images.mjs — do not edit by hand. Run \`npm run images\`.
export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
await writeFile(manifestFile, ts);
console.log(`✓ wrote ${path.relative(root, manifestFile)}`);
